#!/usr/bin/env node
/**
 * Pack the Yale Bright Star Catalogue (5th rev. ed., CDS V/50, public domain) into
 * `src/render/data/brightStars.ts`.
 *
 *   curl -O http://tdc-www.harvard.edu/catalogs/bsc5.dat.gz   (or CDS: ftp/V/50/catalog.gz)
 *   gunzip bsc5.dat.gz
 *   node scripts/build-stars.mjs path/to/bsc5.dat
 *
 * Each star is 6 bytes, little-endian: RA (uint16, fraction of 360°), Dec (int16, fraction of
 * 90°), V magnitude (uint8, (V + 2) × 25) and B−V (int8, × 50; 127 = unknown). That is ~20″ of
 * position error, far below a pixel on the sky sphere. Entries without a J2000 position or V
 * magnitude (a few novae and non-stellar objects) are skipped.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const BV_UNKNOWN = 127;

const src = process.argv[2];
if (!src) {
  console.error('usage: node scripts/build-stars.mjs path/to/bsc5.dat');
  process.exit(1);
}

/** 1-based inclusive byte columns, as in the catalogue ReadMe. */
const col = (line, from, to) => line.slice(from - 1, to).trim();

const stars = [];
for (const line of readFileSync(src, 'latin1').split('\n')) {
  const rah = col(line, 76, 77);
  const vmag = col(line, 103, 107);
  if (!rah || !vmag) continue;
  const ra = (Number(rah) + Number(col(line, 78, 79)) / 60 + Number(col(line, 80, 83)) / 3600) * 15;
  const sign = col(line, 84, 84) === '-' ? -1 : 1;
  const dec =
    sign *
    (Number(col(line, 85, 86)) + Number(col(line, 87, 88)) / 60 + Number(col(line, 89, 90)) / 3600);
  const bvText = col(line, 110, 114);
  stars.push({ ra, dec, mag: Number(vmag), bv: bvText ? Number(bvText) : null });
}

const bytes = new Uint8Array(stars.length * 6);
const view = new DataView(bytes.buffer);
const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));
stars.forEach((s, i) => {
  const o = i * 6;
  view.setUint16(o, Math.round((s.ra / 360) * 65_536) % 65_536, true);
  view.setInt16(o + 2, Math.round(clamp(s.dec / 90, -1, 1) * 32_767), true);
  view.setUint8(o + 4, clamp(Math.round((s.mag + 2) * 25), 0, 255));
  view.setInt8(o + 5, s.bv === null ? BV_UNKNOWN : clamp(Math.round(s.bv * 50), -126, 126));
});

const b64 = Buffer.from(bytes).toString('base64');
const chunks = b64.match(/.{1,90}/g) ?? [];
const out = `// Generated by scripts/build-stars.mjs from the Yale Bright Star Catalogue (5th rev. ed.,
// Hoffleit & Warren 1991, CDS V/50; public domain). Do not edit by hand.

/** Number of stars packed in \`BRIGHT_STARS_B64\`. */
export const BRIGHT_STAR_COUNT = ${stars.length};

/** 6 bytes per star; see \`decodeBrightStars\` in \`render/stars.ts\` for the layout. */
export const BRIGHT_STARS_B64 = [
${chunks.map((c) => `  '${c}',`).join('\n')}
].join('');
`;
writeFileSync(new URL('../src/render/data/brightStars.ts', import.meta.url), out);
console.log(`${stars.length} stars, ${bytes.length} bytes`);
